import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
const sha=(s)=>createHash("sha256").update(s).digest("base64");
const site=readFileSync("src/generated/site.ts","utf8");
const csp=site.match(/export const CSP = "([^"]*)"/)[1].replace(/\\"/g,'"');
const html=site.match(/export const INDEX_HTML = "([\s\S]*?)"\n/)[1].replace(/\\r\\n/g,"\r\n").replace(/\\"/g,'"').replace(/\\\\/g,"\\");
const cspH=[...csp.matchAll(/sha256-([A-Za-z0-9+\/=]+)/g)].map(m=>m[1]);
const s=[...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(m=>sha(m[1]));
console.log("CSP hash count:",cspH.length);
console.log("INDEX_HTML inline script hashes:",s.length);
console.log("every INDEX_HTML script hash in CSP?", s.every(h=>cspH.includes(h)));
const st=[...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(m=>sha(m[1]));
console.log("style hashes in CSP?", st.every(h=>cspH.includes(h)));
