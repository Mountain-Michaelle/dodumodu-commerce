// scripts/build-site.mjs — zero dependencies, Node 18+
// Reads the built storefront from dodumodu_site/dist/, inlines the CSS into
// the root HTML, extracts the content-hashed JS URL, computes strict CSP hashes
// for the remaining inline blocks, and writes src/generated/site.ts.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const __dirname = dirname(fileURLToPath(import.meta.url))
const IN = process.env.WEB_DIR ?? join(__dirname, '..', '..', 'dodumodu_site', 'dist')
const OUT = process.env.OUT ?? join(__dirname, '..', 'src', 'generated', 'site.ts')
const read = (f) => readFileSync(join(IN, f), 'utf8')
const sha = (s, enc) => createHash('sha256').update(s).digest(enc)

// The storefront root is the product page served at /
let html = read('products/glow-serum/index.html')

// 1) inline the CSS: the browser can paint from the HTML alone
const LINK = /<link[^>]*rel="stylesheet"[^>]*href="([^"]+\.css)">/
const linkMatch = html.match(LINK)
if (!linkMatch) throw new Error('index.html must contain <link rel="stylesheet" href="...">')
const cssFile = linkMatch[1] // e.g. "site.00f6049f.min.css"
const css = read(cssFile)
html = html.replace(LINK, () => `<style>${css}</style>`)

// 2) content-hashed JS URL (already hashed by esbuild)
const SCRIPT = /<script[^>]*src="([^"]+\.js)"[^>]*><\/script>/
const jsMatch = html.match(SCRIPT)
if (!jsMatch) throw new Error('index.html must contain <script src="..." defer></script>')
const jsPath = jsMatch[1] // e.g. "/site.b1deab2c.min.js" (already includes leading / from HTML)
const js = read(jsMatch[1])

// 3) a strict CSP needs: no inline style="" attributes, no on*="..." handlers
const bad = html.match(/\sstyle="|\son[a-z]+="/)
if (bad) throw new Error(`index.html still has an inline style/handler attribute: ${bad[0]}`)

// 4) CSP hashes for the inline blocks that remain (<script> and <style> without src)
const inline = (tag) =>
  [...html.matchAll(new RegExp(`<${tag}(?![^>]*\\bsrc=)[^>]*>([\\s\\S]*?)</${tag}>`, 'g'))]
    .map((m) => `'sha256-${sha(m[1], 'base64')}'`)

const CSP = [
  `default-src 'none'`,
  `script-src 'self' ${inline('script').join(' ')}`,
  `style-src ${inline('style').join(' ')}`,
  `img-src 'self' data:`,
  `connect-src 'self'`,
  `base-uri 'none'`,
  `form-action 'self'`,
  `frame-ancestors 'none'`,
].join('; ')

const etag = (s) => `"${sha(s, 'hex').slice(0, 16)}"`
const lit = (k, v) => `export const ${k} = ${JSON.stringify(v)}\n`

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-site.mjs, do not edit\n` +
    lit('INDEX_HTML', html) + lit('INDEX_ETAG', etag(html)) +
    lit('APP_JS', js) + lit('APP_JS_PATH', jsPath) + lit('APP_JS_ETAG', etag(js)) + lit('CSP', CSP),
)
const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(1) + ' KB'
console.log(`built ${OUT}\n  index.html ${kb(html)} (css inlined)  ${jsPath} ${kb(js)}\n  CSP hashes: ${inline('script').length} script, ${inline('style').length} style`)