import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
const sha=(s)=>createHash("sha256").update(s).digest("base64");
const site = readFileSync("src/generated/site.ts","utf8");
const csp = site.match(/export const CSP = "([^"]*)"/)[1].replace(/\\"/g,'"');
const products = JSON.parse(site.match(/PRODUCTS = (\{.*\})\n/)[1]);
const html = products["glow-serum"].html;
const inlineScripts = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(m=>sha(m[1]));
const inlineStyles = [...html.matchAll(/<style(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/style>/g)].map(m=>sha(m[1]));
const cspHashes = [...csp.matchAll(/sha256-([A-Za-z0-9+/=]+)/g)].map(m=>m[1]);
console.log("CSP hashes (count):", cspHashes.length);
console.log("rendered page inline script hashes:", inlineScripts);
console.log("rendered page inline style hashes:", inlineStyles);
console.log("MATCH set:", JSON.stringify(cspHashes)===JSON.stringify([...inlineScripts,...inlineStyles]));
console.log("script hashes present in CSP?:", inlineScripts.every(h=>cspHashes.includes(h)));
console.log("style hashes present in CSP?:", inlineStyles.every(h=>cspHashes.includes(h)));
console.log("--- body starts with raw JSON-LD? ---");
console.log(JSON.stringify(html.slice(html.indexOf("<body"), html.indexOf("<body")+120)));
console.log("has <script type=application/ld+json>:", /<script[^>]*application\/ld\+json/.test(html));
console.log("--- referenced asset ---");
console.log("script src:", html.match(/<script[^>]*src="([^"]+)"/)?.[1]);
